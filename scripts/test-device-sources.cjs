const assert = require('node:assert/strict');
const fs = require('node:fs');
const load = path => import('data:text/javascript;base64,' + Buffer.from(fs.readFileSync(path, 'utf8')).toString('base64'));
(async () => {
  const temperature = await load('app/api/temperature/route.js');
  process.env.TEMPERATURE_FIREBASE_URL = 'https://temperature.example';
  process.env.TEMPERATURE_FIREBASE_AUTH = 'temp-secret';
  let value = 98.1;
  global.fetch = async url => {
    assert.equal(url.hostname, 'temperature.example');
    assert.equal(url.pathname, '/temperature.json');
    assert.equal(url.searchParams.get('auth'), 'temp-secret');
    return Response.json(value);
  };
  assert.deepEqual(await (await temperature.GET()).json(), { temperature: 98.1, unit: '°F', source: 'Temperature device' });
  value = 97.7;
  assert.equal((await (await temperature.GET()).json()).temperature, 97.7);
  for (value of [null, true, {}, '', 'bad']) assert.equal((await temperature.GET()).status, 502);
  const control = await load('app/api/bp-control/route.js');
  process.env.BP_CONTROL_FIREBASE_URL = 'https://control.example';
  process.env.BP_CONTROL_FIREBASE_AUTH = 'control-secret';
  const calls = [];
  let failOn = false, failOff = false;
  global.fetch = async (url, options) => {
    assert.equal(url.hostname, 'control.example');
    assert.equal(url.pathname, '/control/state.json');
    assert.equal(url.searchParams.get('auth'), 'control-secret');
    if (!options.method) return Response.json('OFF');
    const state = JSON.parse(options.body);
    calls.push([state, Date.now()]);
    if ((state === 'ON' && failOn) || (state === 'OFF' && failOff)) throw new Error('Network error');
    return Response.json(state);
  };
  assert.equal((await control.GET()).status, 200);
  assert.equal(calls.length, 0, 'Reading state must never trigger hardware');
  const request = action => new Request('http://localhost/api/bp-control', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ action }) });
  const pending = control.POST(request('ON'));
  await new Promise(resolve => setTimeout(resolve, 20));
  assert.equal((await control.POST(request('ON'))).status, 409);
  assert.equal((await pending).status, 200);
  assert.deepEqual(calls.map(c => c[0]), ['ON', 'OFF']);
  assert.ok(calls[1][1] - calls[0][1] >= 1900);
  calls.length = 0; failOn = true;
  assert.equal((await control.POST(request('ON'))).status, 502);
  assert.deepEqual(calls.map(c => c[0]), ['ON', 'OFF'], 'Attempt OFF after uncertain ON');
  failOff = true;
  assert.equal((await control.POST(request('OFF'))).status, 502);
  failOff = false;
  assert.equal((await control.POST(request('OFF'))).status, 200);
  assert.equal((await control.POST(request('invalid'))).status, 400);
  const { bpCommand } = await import('../app/bp-control.mjs');
  for (const command of ['on bp', 'BP on', 'turn on blood pressure', 'பிபி இயக்கு', 'బీపీ ఆన్', 'बीपी चालू']) assert.equal(bpCommand(command), 'ON');
  for (const command of ['BP off', 'turn off bp', 'பிபி அணை', 'బీపీ ఆఫ్', 'बीपी बंद']) assert.equal(bpCommand(command), 'OFF');
  for (const command of ['blood pressure', 'do not turn on bp', 'how to turn on bp', 'mic off', 'temperature on']) assert.equal(bpCommand(command), null);
  console.log('PASS: separate sources, Fahrenheit, BP pulse timing, OFF on failure, errors and explicit multilingual voice commands. No real hardware writes.');
})().catch(error => { console.error(error); process.exitCode = 1; });
